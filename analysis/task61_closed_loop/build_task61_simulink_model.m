function modelPath = build_task61_simulink_model()
%BUILD_TASK61_SIMULINK_MODEL Create the task 6.1 Simulink block diagram.
%
% The generated model uses the first PI group from task61_config. Change
% task61_Kp and task61_Ki in the MATLAB workspace to test another group.

cfg = task61_config();
model = load_task61_identified_model(cfg);

if ~license("test", "Simulink")
    error("task61:SimulinkUnavailable", ...
        "Simulink is not licensed on this MATLAB installation.");
end
if ~isfolder(cfg.outputDirectory)
    mkdir(cfg.outputDirectory);
end

modelName = char(cfg.simulinkModelName);
modelPath = fullfile(cfg.outputDirectory, modelName + ".slx");

if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
if isfile(modelPath)
    delete(modelPath);
end

assignin("base", "task61_Kp", cfg.piCases.Kp(1));
assignin("base", "task61_Ki", cfg.piCases.Ki(1));
assignin("base", "task61_reference_rad_s", cfg.referenceSpeedRadS);
assignin("base", "task61_step_time_s", cfg.stepTimeS);
assignin("base", "task61_voltage_limit_V", cfg.voltageLimitV);
assignin("base", "task61_plant_num", model.numerator);
assignin("base", "task61_plant_den", model.denominator);

load_system("simulink");
new_system(modelName);
set_param(modelName, ...
    "StopTime", num2str(cfg.stopTimeS), ...
    "SolverType", "Fixed-step", ...
    "Solver", "ode4", ...
    "FixedStep", num2str(cfg.sampleTimeS));

add_block("simulink/Sources/Step", modelName + "/Speed reference", ...
    "Position", [30 90 80 120], ...
    "Time", "task61_step_time_s", ...
    "Before", "0", ...
    "After", "task61_reference_rad_s");
add_block("simulink/Math Operations/Sum", modelName + "/Speed error", ...
    "Position", [120 85 145 125], ...
    "Inputs", "+-");
add_block("simulink/Continuous/Transfer Fcn", modelName + "/PI controller", ...
    "Position", [190 82 295 128], ...
    "Numerator", "[task61_Kp task61_Ki]", ...
    "Denominator", "[1 0]");
add_block("simulink/Discontinuities/Saturation", ...
    modelName + "/Uq voltage limit", ...
    "Position", [340 85 405 125], ...
    "UpperLimit", "task61_voltage_limit_V", ...
    "LowerLimit", "-task61_voltage_limit_V");
add_block("simulink/Continuous/Transfer Fcn", modelName + "/Identified motor", ...
    "Position", [455 80 575 130], ...
    "Numerator", "task61_plant_num", ...
    "Denominator", "task61_plant_den");
add_block("simulink/Signal Routing/Mux", modelName + "/Scope mux", ...
    "Position", [635 75 640 145], ...
    "Inputs", "2");
add_block("simulink/Sinks/Scope", modelName + "/Speed scope", ...
    "Position", [690 85 740 125]);
add_block("simulink/Sinks/To Workspace", modelName + "/Speed data", ...
    "Position", [620 180 720 210], ...
    "VariableName", "task61_speed_simulink", ...
    "SaveFormat", "Structure With Time");
add_block("simulink/Sinks/To Workspace", modelName + "/Uq data", ...
    "Position", [340 180 440 210], ...
    "VariableName", "task61_uq_simulink", ...
    "SaveFormat", "Structure With Time");

add_line(modelName, "Speed reference/1", "Speed error/1", "autorouting", "on");
add_line(modelName, "Speed error/1", "PI controller/1", "autorouting", "on");
add_line(modelName, "PI controller/1", "Uq voltage limit/1", "autorouting", "on");
add_line(modelName, "Uq voltage limit/1", "Identified motor/1", "autorouting", "on");
add_line(modelName, "Uq voltage limit/1", "Uq data/1", "autorouting", "on");
add_line(modelName, "Identified motor/1", "Speed error/2", "autorouting", "on");
add_line(modelName, "Speed reference/1", "Scope mux/1", "autorouting", "on");
add_line(modelName, "Identified motor/1", "Scope mux/2", "autorouting", "on");
add_line(modelName, "Scope mux/1", "Speed scope/1", "autorouting", "on");
add_line(modelName, "Identified motor/1", "Speed data/1", "autorouting", "on");

set_param(modelName, "ZoomFactor", "FitSystem");
save_system(modelName, modelPath);
close_system(modelName, 0);

fprintf("Created Simulink model: %s\n", modelPath);
fprintf("Default PI group: %s, Kp=%.6g, Ki=%.6g\n", ...
    cfg.piCases.Name(1), cfg.piCases.Kp(1), cfg.piCases.Ki(1));
end
